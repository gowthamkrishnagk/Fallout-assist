def settings() -> dict:
    with connect() as db:
        values = {row["key"]: json.loads(row["value_json"])
                  for row in db.execute("SELECT key,value_json FROM settings")}
    return validated_settings(values)


def _cipher():
    from cryptography.fernet import Fernet
    material = hashlib.sha256(("falloutassist-config-v1:" + session_secret()).encode()).digest()
    return Fernet(base64.urlsafe_b64encode(material))


def connection_value(key: str) -> str | None:
    if key not in CONNECTION_DEFAULTS:
        raise KeyError(key)
    with connect() as db:
        row = db.execute("SELECT value FROM connection_config WHERE key=?", (key,)).fetchone()
    if row is None:
        return None
    value = row["value"]
    return _cipher().decrypt(value.encode()).decode() if key in SECRET_KEYS else value


def connection_snapshot() -> dict:
    from .config import config_value
    values = {key: config_value(key) for key in CONNECTION_DEFAULTS if key not in SECRET_KEYS}
    secrets = {}
    for key in SECRET_KEYS:
        with connect() as db:
            row = db.execute("SELECT value FROM connection_config WHERE key=?", (key,)).fetchone()
        secrets[key] = bool(connection_value(key)) if row else bool(os.getenv(key, "").strip())
    return {"values": values, "secrets": secrets}


def update_connection_config(changes: dict, actor: str) -> dict:
    if not isinstance(changes, dict) or not set(changes) <= set(CONNECTION_DEFAULTS):
        raise ValueError("Unknown connection setting")
    for key, value in changes.items():
        if not isinstance(value, str) or len(value) > (4000 if key.endswith("_JQL") else 500):
            raise ValueError(f"Invalid value for {key}")
        value = value.strip()
        if key in {"JIRA_BASE_URL", "AZURE_OPENAI_ENDPOINT"} and value and not value.startswith("https://"):
            raise ValueError(f"{key} must use HTTPS")
        if key == "LANGFUSE_BASE_URL" and value and not value.startswith("https://"):
            raise ValueError("LANGFUSE_BASE_URL must use HTTPS")
        if key == "TLS_CA_BUNDLE" and value and not Path(value).expanduser().is_file():
            raise ValueError("TLS_CA_BUNDLE must point to an existing CA bundle file")
        if key == "JIRA_HISTORY_BACKEND" and value not in {"rovo", "local"}:
            raise ValueError("JIRA_HISTORY_BACKEND must be rovo or local")
        if key in {"JIRA_FEEDBACK_FIELD_ID", "JIRA_SUGGESTED_WORKAROUND_FIELD_ID"} and value and not re.fullmatch(r"customfield_\d+", value):
            raise ValueError(f"Invalid Jira field ID: {key}")
        if key == "EMBEDDING_MODEL" and value != connection_snapshot()["values"][key] and usable_document_count():
            raise ValueError("Change the embedding model only before history ingestion; existing vectors need a rebuild")
    with connect() as db:
        db.execute("BEGIN IMMEDIATE")
        for key, value in changes.items():
            encoded = _cipher().encrypt(value.strip().encode()).decode() if key in SECRET_KEYS else value.strip()
            db.execute("INSERT INTO connection_config(key,value,changed_at) VALUES (?,?,?) "
                       "ON CONFLICT(key) DO UPDATE SET value=excluded.value,changed_at=excluded.changed_at",
                       (key, encoded, utc_now()))
        db.execute("INSERT INTO app_state(key,value) VALUES (?,?) "
                   "ON CONFLICT(key) DO UPDATE SET value=excluded.value",
                   ("connection_version", utc_now()))
        _append_audit(db, actor, "connection_config_changed", "settings",
                      {"keys": sorted(changes)})
    return connection_snapshot()


def update_settings(changes: dict, actor: str) -> dict:
    if not set(changes) <= set(DEFAULTS):
        raise ValueError("Unknown setting")
    new = validated_settings({**settings(), **changes})
    with connect() as db:
        db.execute("BEGIN IMMEDIATE")
        for key in changes:
            db.execute("UPDATE settings SET value_json=?,changed_at=? WHERE key=?",
                       (_json(new[key]), utc_now(), key))
        _append_audit(db, actor, "settings_changed", "settings",
                      {"changed": {key: new[key] for key in changes}})
    return new


def audit(actor: str, action: str, subject: str, data: dict) -> int:
    """Append a hash-linked event. Caller must pass redacted data only."""
    with connect() as db:
        db.execute("BEGIN IMMEDIATE")
        return _append_audit(db, actor, action, subject, data)


def _append_audit(db: sqlite3.Connection | PostgresConnection, actor: str, action: str,
                  subject: str, data: dict) -> int:
    if isinstance(db, PostgresConnection):
        db.execute("SELECT pg_advisory_xact_lock(60499217)")
    previous = db.execute("SELECT event_hash FROM audit_events ORDER BY id DESC LIMIT 1").fetchone()
    previous_hash = previous["event_hash"] if previous else "0" * 64
    created = utc_now()
    body = _json({"created_at": created, "actor": actor, "action": action,
                  "subject": subject, "data": data, "previous_hash": previous_hash})
    event_hash = hashlib.sha256(body.encode("utf-8")).hexdigest()
    cursor = db.execute(
        "INSERT INTO audit_events(created_at,actor,action,subject,data_json,previous_hash,event_hash) "
        "VALUES (?,?,?,?,?,?,?)" + (" RETURNING id" if isinstance(db, PostgresConnection) else ""),
        (created, actor, action, subject, _json(data), previous_hash, event_hash),
    )
    return int(cursor.fetchone()["id"] if isinstance(db, PostgresConnection) else cursor.lastrowid)


def recent_audit(limit: int = 100) -> list[dict]:
    with connect() as db:
        rows = db.execute("SELECT * FROM audit_events ORDER BY id DESC LIMIT ?", (limit,)).fetchall()
    return [{**dict(row), "data": json.loads(row["data_json"])} for row in rows]


def verify_audit() -> dict:
    previous_hash = "0" * 64
    count = 0
    with connect() as db:
        for row in db.execute("SELECT * FROM audit_events ORDER BY id"):
            body = _json({"created_at": row["created_at"], "actor": row["actor"],
                          "action": row["action"], "subject": row["subject"],
                          "data": json.loads(row["data_json"]),
                          "previous_hash": previous_hash})
            calculated = hashlib.sha256(body.encode("utf-8")).hexdigest()
            if row["previous_hash"] != previous_hash or row["event_hash"] != calculated:
                return {"ok": False, "checked": count, "first_bad_id": row["id"]}
            previous_hash = calculated
            count += 1
    return {"ok": True, "checked": count, "head_hash": previous_hash}


