class PostgresConnection:
    """Small DB-API bridge, keeping SQL and transactions in this module."""

    def __init__(self, url: str) -> None:
        import psycopg
        from psycopg.rows import dict_row
        self.raw = psycopg.connect(url, row_factory=dict_row, connect_timeout=10)

    def execute(self, sql: str, params: tuple | list = ()):
        if sql.strip().upper() == "BEGIN IMMEDIATE":
            return None
        return self.raw.execute(sql.replace("?", "%s"), params)

    def executemany(self, sql: str, rows: list[tuple]):
        with self.raw.cursor() as cursor:
            cursor.executemany(sql.replace("?", "%s"), rows)

    def executescript(self, script: str) -> None:
        for statement in script.split(";"):
            statement = statement.strip()
            if not statement or statement.upper().startswith("CREATE VIRTUAL TABLE"):
                continue
            statement = statement.replace("INTEGER PRIMARY KEY AUTOINCREMENT",
                                          "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
            self.execute(statement)
        self.execute("CREATE INDEX IF NOT EXISTS idx_source_docs_fts ON source_docs "
                     "USING GIN (to_tsvector('simple', "
                     "coalesce(summary,'') || ' ' || coalesce(step,'') || ' ' || "
                     "coalesce(error,'') || ' ' || coalesce(body,'')))")

    def commit(self) -> None:
        self.raw.commit()

    def rollback(self) -> None:
        self.raw.rollback()

    def close(self) -> None:
        self.raw.close()


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _json(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


@contextmanager
def connect(path: Path = DATABASE_PATH) -> Iterator[sqlite3.Connection | PostgresConnection]:
    if database_backend() == "postgres":
        url = os.getenv("DATABASE_URL", "").strip()
        if not url:
            raise RuntimeError("DATABASE_URL is required for PostgreSQL; set DATABASE_BACKEND=sqlite for local fallback")
        db = PostgresConnection(url)
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        db = sqlite3.connect(str(path), timeout=30)
        db.row_factory = sqlite3.Row
        db.execute("PRAGMA journal_mode=WAL")
        db.execute("PRAGMA foreign_keys=ON")
    try:
        yield db
        db.commit()
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


